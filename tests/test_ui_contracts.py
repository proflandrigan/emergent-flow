def test_graph_mutation_fixture_round_trips() -> None:
    """The committed sample GraphMutation fixture (tests/fixtures/graph_mutation_sample.json)
    deserializes back to an identical GraphMutation -- the Python-side half of the
    cross-language contract; a UI-side ajv test can validate the SAME file against
    mutation.schema.json (out of scope here, see Story 4's validateMutation.test.ts)."""
    from emergentflow.ir.mutation import GraphMutation

    fixture_path = REPO_ROOT / "tests" / "fixtures" / "graph_mutation_sample.json"
    data = json.loads(fixture_path.read_text())
    mutation = GraphMutation.model_validate(data)
    assert mutation.model_dump(mode="json") == data
