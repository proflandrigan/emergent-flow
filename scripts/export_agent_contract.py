#!/usr/bin/env python3
"""Generate ``emergentflow/collab/reply_contract.py`` from ``agents/_reply-contract.md``.

The agent reply contract is authored once in markdown. This script renders it into a
checked-in Python module so the runtime never has to read a file (wheel installs may
not ship ``agents/``). CI runs ``--check`` and fails when the generated module is stale.

Usage::

    uv run python scripts/export_agent_contract.py           # regenerate
    uv run python scripts/export_agent_contract.py --check   # verify, no writes
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "agents" / "_reply-contract.md"
TARGET = REPO / "emergentflow" / "collab" / "reply_contract.py"


def render(markdown: str) -> str:
    """Return the full text of the generated module embedding ``markdown``."""
    if '"""' in markdown or "\\" in markdown:
        raise ValueError(
            "reply contract markdown must not contain triple quotes or backslashes; "
            "they would break or alter the generated string literal"
        )
    body = markdown if markdown.endswith("\n") else markdown + "\n"
    return (
        '''# ruff: noqa: E501 -- generated; the contract's markdown lines are not wrapped.
"""
emergentflow.collab.reply_contract
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
GENERATED by scripts/export_agent_contract.py from agents/_reply-contract.md -- do not edit by
hand. Re-run ``uv run python scripts/export_agent_contract.py`` after editing the markdown; CI
runs it with ``--check`` and fails on drift.

The shared agent reply contract (issue #173), injected into the in-app chat prompt
(``chat_runner``) and the Mode-B consult system prompt (``consult``). Stdlib-free constant:
importing this module pulls in nothing (works-without-agents invariant, ADR 0019).
"""

from __future__ import annotations

REPLY_CONTRACT = """\\
'''
        + body
        + '''"""
'''
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the generated module is missing or stale; do not write",
    )
    args = parser.parse_args(argv)

    rendered = render(SOURCE.read_text(encoding="utf-8"))

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
        if current == rendered:
            print("reply contract up to date")
            return 0
        print(
            "emergentflow/collab/reply_contract.py is stale; "
            "run: uv run python scripts/export_agent_contract.py",
            file=sys.stderr,
        )
        return 1

    with TARGET.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)
    print("wrote emergentflow/collab/reply_contract.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
